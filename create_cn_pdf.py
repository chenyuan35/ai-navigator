class ProductPDF(FPDF):
    def __init__(self):
        super().__init__()
        self.add_font('CJK', '', FONT_PATH, uni=True)
    
    def header(self):
        self.set_font('CJK', '', 8)
        self.set_text_color(150, 150, 150)
        self.cell(0, 6, 'AI 赚钱工具包 | 50 个高转化 ChatGPT Prompts', 0, 1, 'C')
        self.set_draw_color(0, 150, 255)
        self.set_line_width(0.3)
        self.line(10, 15, 200, 15)
        self.ln(3)
    
    def footer(self):
        self.set_y(-12)
        self.set_font('CJK', '', 7)
        self.set_text_color(150, 150, 150)
        self.cell(0, 5, f'AI 赚钱工具包 2026 | 第 {self.page_no()} 页', 0, 0, 'C')


def create_pdf():
    pdf = ProductPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    
    # ===== 封面 =====
    pdf.add_page()
    pdf.ln(30)
